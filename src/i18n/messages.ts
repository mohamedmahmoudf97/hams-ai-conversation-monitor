export type Locale = 'en' | 'ar';

const createFormatters = (locale: Locale) => ({
  number: new Intl.NumberFormat(locale),
  plural: new Intl.PluralRules(locale),
  time: new Intl.DateTimeFormat(locale, { hour: '2-digit', minute: '2-digit' }),
  dateTime: new Intl.DateTimeFormat(locale, { dateStyle: 'medium', timeStyle: 'short' }),
});
export const formatters = { en: createFormatters('en'), ar: createFormatters('ar') };

type Plurals = Partial<Record<Intl.LDMLPluralRule, string>> & { other: string };
const countLabel = (locale: Locale, forms: Plurals) => (count: number) =>
  (forms[formatters[locale].plural.select(count)] ?? forms.other).replace(
    '{count}',
    formatters[locale].number.format(count),
  );

